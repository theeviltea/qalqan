// Builds src/theme/tokens.ts and src/icons/icons.ts from design/ (exports of the Qalqan Design System).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), 'utf8'));
const src = read('../design/tokens.json');
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => (typeof v === 'string' && v.endsWith('px') ? Number(v.slice(0, -2)) : v);

const themes = src.color.themes.map((t) => t.id);
const colors = {};
for (const theme of themes) {
  colors[theme] = Object.fromEntries(
    src.color.tokens.map((t) => [camel(t.name), typeof t.value === 'string' ? t.value : t.value[theme] ?? t.value[themes[0]]]),
  );
}
const spacing = Object.fromEntries(src.spacing.tokens.map((t) => [camel(t.name), px(t.value)]));
const radius = Object.fromEntries(src.radius.tokens.map((t) => [camel(t.name), px(t.value)]));
const blur = Object.fromEntries((src.blur?.tokens ?? []).map((t) => [camel(t.name), px(t.value)]));
const shadows = Object.fromEntries((src.shadow?.tokens ?? []).map((t) => [camel(t.name), t.value]));

// "linear-gradient(115deg, #0E2BB0 0%, #3A1FD0 55%, #8A0BF7 100%)" -> { angle, colors, locations, css }
const gradients = Object.fromEntries(
  (src.gradient?.tokens ?? []).map((t) => {
    const angle = Number((t.value.match(/(\d+)deg/) || [0, 115])[1]);
    const stops = [...t.value.matchAll(/(#[0-9A-Fa-f]{3,8}|rgba?\([^)]*\))\s*(\d+%)?/g)];
    const cols = stops.map((m) => m[1]);
    const locs = stops.map((m, i) => (m[2] ? Number(m[2].slice(0, -1)) / 100 : i / Math.max(1, stops.length - 1)));
    return [camel(t.name), { angle, colors: cols, locations: locs, css: t.value }];
  }),
);

const type = {};
for (const g of src.type.groups) for (const s of g.styles) {
  type[camel(s.name)] = { family: g.family, fontSize: px(s.fontSize), lineHeight: px(s.lineHeight), fontWeight: s.fontWeight };
}

const j = (v) => JSON.stringify(v, null, 2);
writeFileSync(
  new URL('../src/theme/tokens.ts', import.meta.url),
  `// GENERATED by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand.
// Source of truth: Qalqan Design System. Re-export tokens.json there and run \`npm run tokens\`.

export const palette = ${j(colors)} as const;

export type ColorScheme = keyof typeof palette;
export type Colors = { [K in keyof (typeof palette)['light']]: string };

export const spacing = ${j(spacing)} as const;

export const radius = ${j(radius)} as const;

export const blur = ${j(blur)} as const;

export const shadows = ${j(shadows)} as const;

export const gradients = ${j(gradients)} as const;

export type GradientName = keyof typeof gradients;

export const typeScale = ${j(type)} as const;
`,
);

const icons = read('../design/icons.json');
const names = read('../design/icon-names.json');
const out = Object.fromEntries(Object.entries(icons).map(([k, v]) => [names[k] ?? k, v]));
writeFileSync(
  new URL('../src/icons/icons.ts', import.meta.url),
  `// GENERATED by scripts/build-tokens.mjs from design/icons.json — Huge Icons, stroke rounded 1.5px (same pack as 919).
// Each value is the inner SVG markup of a 24x24 icon; colour comes from \`currentColor\`.
export const icons = ${j(out)} as const;

export type IconName = keyof typeof icons;
`,
);
console.log(`tokens: ${Object.keys(colors.light).length} colors, ${Object.keys(gradients).length} gradients; icons: ${Object.keys(out).length}`);
